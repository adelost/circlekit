// rules.mjs: the kinds that read files as text, and the judge that turns hits into counts and red lines; no node API (Cut row 1880), so the node run
// (arch-check.mjs) and the browser entry (web.mjs) count with the same code. A repo is {files, read(file), covered(rule)}, plus what story.mjs asks of it.

const toRegExp = glob => new RegExp("^" + glob.replace(/[.+^${}()|[\]\\]/g, "\\$&").replace(/\*\*\//g, "\u0000").replace(/\*\*/g, "\u0001").replace(/\*/g, "[^/]*").replace(/\u0000/g, "(?:.*/)?").replace(/\u0001/g, ".*") + "$");
export const matcher = globs => { const all = [globs ?? []].flat().map(toRegExp); return path => all.some(re => re.test(path)); };
export const lines = text => text.split("\n");
/** The lines an editor numbers: the empty piece after a closing newline is none. */
export const lineCount = text => text === "" ? 0 : lines(text).length - (text.endsWith("\n") ? 1 : 0);
/** The files whose language opens a comment with #: Python, shell, YAML, TOML, Ruby, R, Perl, PowerShell, Terraform, Nix, config files, a Makefile,
 *  a Dockerfile. Elsewhere a line that starts with # is code (a CSS id selector, a JS private name, a C directive, a Markdown heading) and is counted. */
const HASH_COMMENTS = /\.(?:py|pyi|sh|bash|zsh|ya?ml|toml|rb|r|pl|ps1|tf|nix|conf|cfg|ini|properties|env|mk|cmake)$|(?:^|\/)(?:Makefile|Dockerfile[\w.-]*|\w+\.dockerfile|Gemfile|Rakefile|Procfile|CMakeLists\.txt|\.env[\w.-]*|\.gitignore|\.dockerignore|\.npmrc|\.editorconfig)$/i;
/** A line that is not a comment of its file's language: //, /* and * open one in every file, a shebang (#!) is no code either, # only where HASH_COMMENTS says. */
export const noteless = (line, file) => !/^\s*(\/\/|\*|\/\*|#!)/.test(line) && !(HASH_COMMENTS.test(file) && /^\s*#/.test(line));
/** A generated file: `generated` in its path (catalog.generated.ts, src/media/generated/), or a comment in its first five lines that says so
 *  (GENERATED by, @generated, Do not edit), as the generators of Cut and ai-gateway write their heads. */
export const generated = (file, text) => /(^|[/.])generated([/.]|$)/i.test(file)
  || lines(text).slice(0, 5).some(line => !noteless(line, file) && /@generated|\bgenerated by\b|\bdo not edit\b/i.test(line));

